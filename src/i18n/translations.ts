export type Language = 'ar' | 'fr' | 'en';

export const formatDZD = (amount: number | undefined | null): string => {
  if (amount === undefined || amount === null || isNaN(amount)) {
    return '0 DA';
  }
  // Integer formatting with spaces: 1 500 DA
  const formatted = Math.round(amount)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  return `${formatted} DA`;
};

